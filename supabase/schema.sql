-- ---------- one-time data import from the Google Sheet (downloaded as QS CRM DB.xlsx) ----------
create or replace function public.crm_migrate(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public set timezone to 'Asia/Brunei' as $$
declare me profiles := crm_need(false, true); n_t int; n_b int; n_a int; n_r int; n_l int; existing int;
begin
  select count(*) into existing from tenders;
  if existing > 0 and not coalesce((p ->> 'replace')::boolean, false) then
    raise exception 'The database already has % tenders. Tick "Replace" to delete them and import again.', existing;
  end if;
  -- "where true": Supabase (pg-safeupdate) refuses a DELETE without a WHERE clause
  delete from activity_log where true; delete from revisions where true; delete from asbuilt_items where true; delete from bq_items where true; delete from tenders where true;
  insert into tenders select * from jsonb_populate_recordset(null::tenders, coalesce(p -> 'tenders', '[]'));
  get diagnostics n_t = row_count;
  insert into bq_items (arza_no, bq_set, item_id, bill, page, item, heading, description, unit, qty, rate, amount, provisional, remarks, source, imported_at)
  select arza_no, bq_set, item_id, bill, page, item, heading, description, unit, qty, rate, amount, provisional, remarks, source, coalesce(imported_at, now())
  from jsonb_populate_recordset(null::bq_items, coalesce(p -> 'bq', '[]'));
  get diagnostics n_b = row_count;
  insert into asbuilt_items (arza_no, measure_set, item_ref_raw, item_id, match_status, level, location, description, unit, nos, l, w, h, qty, remark, measured_by, measured_date, source_file, source_row, imported_at)
  select arza_no, measure_set, item_ref_raw, item_id, match_status, level, location, description, unit, nos, l, w, h, qty, remark, measured_by, measured_date, source_file, source_row, coalesce(imported_at, now())
  from jsonb_populate_recordset(null::asbuilt_items, coalesce(p -> 'asbuilt', '[]'));
  get diagnostics n_a = row_count;
  insert into revisions select * from jsonb_populate_recordset(null::revisions, coalesce(p -> 'revisions', '[]'));
  get diagnostics n_r = row_count;
  insert into activity_log (ts, action, arza_no, detail, user_name, tx)
  select coalesce(ts, now()), action, arza_no, detail, user_name, 0 from jsonb_populate_recordset(null::activity_log, coalesce(p -> 'log', '[]'));
  get diagnostics n_l = row_count;
  if jsonb_typeof(p -> 'lists') = 'object' then
    insert into lists (list, value, sort)
    select k, v, o::int from jsonb_each(p -> 'lists') e(k, arr), jsonb_array_elements_text(arr) with ordinality x(v, o)
    on conflict (list, value) do update set sort = excluded.sort;
  end if;
  perform crm_log('migrate', null, 'Imported from ' || coalesce(nullif(p ->> 'file_name', ''), 'QS CRM DB.xlsx') || ': ' || n_t || ' tenders, ' || n_b || ' BQ lines, '
    || n_a || ' as-built lines, ' || n_r || ' revisions, ' || n_l || ' log lines' || case when existing > 0 then ' (replaced ' || existing || ' tenders)' else '' end);
  return crm_out(jsonb_build_object('tenders', n_t, 'bq', n_b, 'asbuilt', n_a, 'revisions', n_r, 'log', n_l));
end $$;

