create table if not exists public.tenders (
  arza_no text primary key check (arza_no ~ '^T\d+$'),
  tender_ref text, project_no text, title text, title_en text, client text, client_group text, location text,
  tender_type text, id_scheme text,
  site_visit_date date, closing_date timestamp, status text, our_sum numeric(16, 2), completion_period text, submitted_date date,
  locked text not null default 'N' check (locked in ('Y', 'N')), locked_at timestamptz,
  result_date date, winner text, winning_sum numeric(16, 2), diff_pct numeric(9, 4), result_source text,
  workbook_file text, folder_link text, notes text,
  contract_sum numeric(16, 2), contract_rev text,
  created_at timestamptz default now(), updated_at timestamptz default now(),
  created_by uuid, updated_by uuid
);

create table if not exists public.bq_items (
  id bigint generated by default as identity primary key,
  arza_no text not null references public.tenders (arza_no) on update cascade on delete cascade,
  bq_set text not null,                      -- Tendered | R1 | R2 …
  item_id text not null,
