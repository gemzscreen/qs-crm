/* bid result: Won / Lost / Cancelled / No bid */
create or replace function public.crm_result(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public as $$
declare me profiles := crm_need(true); t tenders := crm_tender(p ->> 'arza_no'); r jsonb := coalesce(p -> 'result', '{}'); st text := r ->> 'status'; ws numeric; dp numeric; txt text;
begin
  if st is null or st not in ('Won', 'Lost', 'Cancelled', 'No bid') then raise exception 'Result must be Won, Lost, Cancelled or No bid'; end if;
  ws := case when st = 'Won' then t.our_sum else crm_n(r -> 'winning_sum') end;
  dp := case when ws > 0 and t.our_sum > 0 then round((t.our_sum - ws) / ws, 4) end;
  update tenders set status = st, result_date = coalesce(nullif(r ->> 'result_date', '')::date, crm_today()),
    winner = case when st = 'Won' then 'ARZA SDN BHD' else nullif(r ->> 'winner', '') end, winning_sum = ws, diff_pct = dp,
    result_source = nullif(r ->> 'result_source', ''),
    notes = case when coalesce(r ->> 'notes', '') <> '' then coalesce(notes || ' | ', '') || (r ->> 'notes') else notes end,
    updated_at = now(), updated_by = me.id
  where arza_no = t.arza_no;
  t := crm_tender(t.arza_no);
  txt := st || coalesce(', winner ' || t.winner, '') || coalesce(', B$' || crm_m(t.winning_sum), '') || coalesce(', ours ' || to_char(t.diff_pct * 100, 'FM9999990.0') || '%', '');
  perform crm_log('result', t.arza_no, txt);
  return crm_out(crm_tj(t));
end $$;

