/* new (no rfq_no, or an imported number) or update: p {rfq_no, new, header {...}, items [...]} */
create or replace function public.crm_saverfq(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public set timezone to 'Asia/Brunei' as $$
declare me profiles := crm_need(true); h jsonb := coalesce(p -> 'header', '{}'); its jsonb := coalesce(p -> 'items', '[]'); v_no text := nullif(upper(btrim(coalesce(p ->> 'rfq_no', ''))), '');
  isnew boolean := coalesce((p ->> 'new')::boolean, v_no is null); d date; n int; old rfqs; r rfqs; bad text; req date;
begin
  if btrim(coalesce(h ->> 'title', '')) = '' then raise exception 'Give the RFQ a title (e.g. "SS304 railing tubes & fittings")'; end if;
  if jsonb_typeof(its) <> 'array' or jsonb_array_length(its) = 0 then raise exception 'Add at least one item'; end if;
  if jsonb_array_length(its) > 200 then raise exception 'Too many items (200 max) - split the list into several RFQs'; end if;
  select x ->> 'description' into bad from jsonb_array_elements(its) x where btrim(coalesce(x ->> 'description', '')) = '' limit 1;
  if found then raise exception 'Every item needs a description'; end if;
  select x ->> 'category' into bad from jsonb_array_elements(its) x where coalesce(x ->> 'category', '') <> '' and not exists (select 1 from categories c where c.code = x ->> 'category') limit 1;
  if found then raise exception 'Unknown category %', bad; end if;
  select x ->> 'qty' into bad from jsonb_array_elements(its) x where coalesce(x ->> 'qty', '') <> '' and (x ->> 'qty') !~ '^\d+(\.\d+)?$' limit 1;
  if found then raise exception 'Quantity "%" is not a number', bad; end if;
  if coalesce(h ->> 'urgency', 'RESTOCK') not in ('SUPER URGENT', 'URGENT', 'NORMAL', 'NEEDED SOON', 'RESTOCK') then raise exception 'Unknown urgency %', h ->> 'urgency'; end if;
  d := coalesce(nullif(h ->> 'rfq_date', '')::date, current_date);
  select min(nullif(x ->> 'required_date', '')::date) into req from jsonb_array_elements(its) x;
  if isnew then
    perform pg_advisory_xact_lock(hashtext('qscrm.rfqs'));
    if v_no is null then
      select coalesce(max((substring(rfq_no from '^RFQ-\d{4}-(\d+)'))::int), 0) + 1 into n from rfqs where rfq_no like 'RFQ-' || to_char(d, 'YYMM') || '-%';
      v_no := 'RFQ-' || to_char(d, 'YYMM') || '-' || lpad(n::text, 3, '0');
    elsif exists (select 1 from rfqs where rfq_no = v_no) then raise exception '% already exists', v_no;
    end if;
    insert into rfqs (rfq_no, title, rfq_date, created_by) values (v_no, btrim(h ->> 'title'), d, me.id);
  else
    old := crm_rfqget(v_no);
    if old.status in ('Awarded', 'Cancelled') then raise exception '% is % - it cannot be changed', old.rfq_no, lower(old.status); end if;
  end if;
  update rfqs set title = btrim(h ->> 'title'), project = nullif(btrim(coalesce(h ->> 'project', '')), ''), arza_no = nullif(btrim(coalesce(h ->> 'arza_no', '')), ''),
    mr_ref = nullif(btrim(coalesce(h ->> 'mr_ref', '')), ''), rfq_date = d, required_date = req, urgency = coalesce(nullif(h ->> 'urgency', ''), 'RESTOCK'),
    deadline = nullif(h ->> 'deadline', '')::date, delivery_place = nullif(btrim(coalesce(h ->> 'delivery_place', '')), ''),
    qty_mode = case when h ->> 'qty_mode' in ('firm', 'moq') then h ->> 'qty_mode' else 'firm' end, short_desc = nullif(btrim(coalesce(h ->> 'short_desc', '')), ''),
    certs = nullif(btrim(coalesce(h ->> 'certs', '')), ''), notes = nullif(btrim(coalesce(h ->> 'notes', '')), ''), updated_at = now(), updated_by = me.id
  where rfq_no = v_no returning * into r;
  delete from rfq_items where rfq_no = v_no;
  insert into rfq_items (rfq_no, line, description, short, spec_brand, qty, unit, required_date, category, res_code, only_overseas, notes)
  select v_no, o::int, btrim(x ->> 'description'), nullif(btrim(coalesce(x ->> 'short', '')), ''), nullif(btrim(coalesce(x ->> 'spec_brand', '')), ''),
    nullif(x ->> 'qty', '')::numeric, nullif(btrim(coalesce(x ->> 'unit', '')), ''), nullif(x ->> 'required_date', '')::date, nullif(x ->> 'category', ''),
    nullif(btrim(coalesce(x ->> 'res_code', '')), ''), coalesce((x ->> 'only_overseas')::boolean, false), nullif(btrim(coalesce(x ->> 'notes', '')), '')
  from jsonb_array_elements(its) with ordinality y(x, o);
  perform crm_log('rfq', v_no, case when isnew then 'New RFQ ' || v_no || ' - ' || r.title || ' (' || jsonb_array_length(its) || ' item' || case when jsonb_array_length(its) = 1 then '' else 's' end
    || ', ' || r.urgency || coalesce(', deadline ' || crm_fd(r.deadline), '') || ')' else 'Updated ' || v_no || ' - ' || r.title || ' (' || jsonb_array_length(its) || ' items)' end);
  return crm_out(jsonb_build_object('rfq_no', v_no, 'rfq', crm_rfqj(r)));
end $$;

/* send list: p {rfq_no, add:[{supplier_id, zone, priority, email, whatsapp, phone, status?, emailed_at?, whatsapp_at?, replied_at?, valid_quote?, note?}], remove:[supplier_id]} */
create or replace function public.crm_setrecipients(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public set timezone to 'Asia/Brunei' as $$
declare me profiles := crm_need(true); r rfqs := crm_rfqget(p ->> 'rfq_no'); x jsonb; s suppliers; nadd int := 0; ndel int := 0; names text[] := '{}'; st text;
begin
  if r.status in ('Awarded', 'Cancelled') then raise exception '% is % - the send list cannot change', r.rfq_no, lower(r.status); end if;
  for x in select * from jsonb_array_elements(coalesce(p -> 'add', '[]')) loop
    s := crm_sup(x ->> 'supplier_id');
    if s.status = 'Blacklisted' then raise exception '% % is blacklisted', s.supplier_id, s.name; end if;
    st := coalesce(nullif(x ->> 'status', ''), 'Not contacted');
    if st not in ('Not contacted', 'Emailed', 'WhatsApp sent', 'Reminder 1', 'Reminder 2', 'Replied', 'Quoted', 'Declined', 'No reply', 'Bounced') then raise exception 'Unknown status %', st; end if;
    if coalesce(x ->> 'whatsapp', '') <> '' and x ->> 'whatsapp' !~ '^\+\d{7,15}$' then raise exception 'WhatsApp % must start with +country code', x ->> 'whatsapp'; end if;
    insert into rfq_recipients (rfq_no, supplier_id, zone, priority, email, whatsapp, phone, status, valid_quote, emailed_at, whatsapp_at, replied_at, note, added_by)
    values (r.rfq_no, s.supplier_id, coalesce(nullif(x ->> 'zone', '')::int, s.zone), nullif(x ->> 'priority', '')::int, nullif(lower(btrim(coalesce(x ->> 'email', ''))), ''),
      nullif(x ->> 'whatsapp', ''), nullif(x ->> 'phone', ''), st, (x ->> 'valid_quote')::boolean, nullif(x ->> 'emailed_at', '')::timestamptz,
      nullif(x ->> 'whatsapp_at', '')::timestamptz, nullif(x ->> 'replied_at', '')::timestamptz, nullif(btrim(coalesce(x ->> 'note', '')), ''), me.id)
    on conflict (rfq_no, supplier_id) do update set zone = excluded.zone, priority = coalesce(excluded.priority, rfq_recipients.priority),
      email = coalesce(excluded.email, rfq_recipients.email), whatsapp = coalesce(excluded.whatsapp, rfq_recipients.whatsapp), phone = coalesce(excluded.phone, rfq_recipients.phone),
      status = case when x ? 'status' then excluded.status else rfq_recipients.status end, valid_quote = coalesce(excluded.valid_quote, rfq_recipients.valid_quote),
      emailed_at = coalesce(excluded.emailed_at, rfq_recipients.emailed_at), whatsapp_at = coalesce(excluded.whatsapp_at, rfq_recipients.whatsapp_at),
      replied_at = coalesce(excluded.replied_at, rfq_recipients.replied_at), note = coalesce(excluded.note, rfq_recipients.note), updated_at = now();
    nadd := nadd + 1; names := names || s.supplier_id;
  end loop;
  delete from rfq_recipients where rfq_no = r.rfq_no and supplier_id in (select upper(jsonb_array_elements_text(coalesce(p -> 'remove', '[]')))) and status = 'Not contacted';
  get diagnostics ndel = row_count;
  if jsonb_array_length(coalesce(p -> 'remove', '[]')) > ndel then raise exception 'Suppliers already contacted stay on the send list (set their status instead)'; end if;
  perform crm_rfqauto(r.rfq_no);
  if nadd + ndel > 0 then perform crm_log('rfq', r.rfq_no, 'Send list: ' || case when nadd > 0 then nadd || ' supplier(s) added/updated (' || array_to_string(names[1:8], ', ') || case when nadd > 8 then ', …' else '' end || ')' else '' end
    || case when nadd > 0 and ndel > 0 then ', ' else '' end || case when ndel > 0 then ndel || ' removed' else '' end); end if;
  return crm_out(crm_rfq(jsonb_build_object('rfq_no', r.rfq_no)));
end $$;

/* one click on a send-list button: p {rfq_no, supplier_id, action email|whatsapp|reminder1|reminder2|call} -> timestamps + status */
create or replace function public.crm_rfqclick(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public set timezone to 'Asia/Brunei' as $$
declare me profiles := crm_need(true); r rfqs := crm_rfqget(p ->> 'rfq_no'); a text := coalesce(p ->> 'action', ''); x rfq_recipients; resp boolean;
begin
  if a not in ('email', 'whatsapp', 'reminder1', 'reminder2', 'call', 'thanks', 'regret') then raise exception 'Unknown action %', a; end if;
  if r.status = 'Cancelled' then raise exception '% is cancelled', r.rfq_no; end if;
  select * into x from rfq_recipients where rfq_no = r.rfq_no and supplier_id = upper(p ->> 'supplier_id') for update;
  if not found then raise exception '% is not on the send list of %', p ->> 'supplier_id', r.rfq_no; end if;
  resp := x.status in ('Replied', 'Quoted', 'Declined');
  update rfq_recipients set
    emailed_at = case when a = 'email' then coalesce(emailed_at, now()) else emailed_at end,
    whatsapp_at = case when a = 'whatsapp' then coalesce(whatsapp_at, now()) else whatsapp_at end,
    reminder1_at = case when a = 'reminder1' then coalesce(reminder1_at, now()) else reminder1_at end,
    reminder2_at = case when a = 'reminder2' then coalesce(reminder2_at, now()) else reminder2_at end,
    status = case when resp or status in ('Bounced') then status
      when a = 'email' and status = 'Not contacted' then 'Emailed'
      when a = 'whatsapp' and status in ('Not contacted', 'Emailed') then 'WhatsApp sent'
      when a = 'reminder1' and status in ('Not contacted', 'Emailed', 'WhatsApp sent', 'No reply') then 'Reminder 1'
      when a = 'reminder2' and status in ('Not contacted', 'Emailed', 'WhatsApp sent', 'Reminder 1', 'No reply') then 'Reminder 2'
      else status end,
    updated_at = now()
  where rfq_no = r.rfq_no and supplier_id = x.supplier_id returning * into x;
  insert into rfq_clicks (rfq_no, supplier_id, action, user_id, user_name) values (r.rfq_no, x.supplier_id, a, me.id, coalesce(nullif(me.display_name, ''), me.full_name, me.email));
  perform crm_rfqauto(r.rfq_no);
  return jsonb_build_object('recipient', crm_recj(x), 'rfq_status', (select status from rfqs where rfq_no = r.rfq_no));
end $$;

/* status buttons: p {rfq_no, supplier_id, status, valid_quote, note, at}. Replied / Quoted / Declined -> supplier Verified (real reply);
   Bounced with no phone or WhatsApp on file -> supplier Failed. */
create or replace function public.crm_setrecipient(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public set timezone to 'Asia/Brunei' as $$
declare me profiles := crm_need(true); r rfqs := crm_rfqget(p ->> 'rfq_no'); x rfq_recipients; s suppliers; st text := coalesce(p ->> 'status', ''); old text; oldv boolean; msg text;
begin
  if st not in ('Not contacted', 'Emailed', 'WhatsApp sent', 'Reminder 1', 'Reminder 2', 'Replied', 'Quoted', 'Declined', 'No reply', 'Bounced') then raise exception 'Unknown status %', st; end if;
  select * into x from rfq_recipients where rfq_no = r.rfq_no and supplier_id = upper(p ->> 'supplier_id') for update;
  if not found then raise exception '% is not on the send list of %', p ->> 'supplier_id', r.rfq_no; end if;
  old := x.status; oldv := x.valid_quote; s := crm_sup(x.supplier_id);
  update rfq_recipients set status = st,
    replied_at = case when st in ('Replied', 'Quoted', 'Declined') then coalesce(replied_at, nullif(p ->> 'at', '')::timestamptz, now()) when st in ('Not contacted', 'Emailed', 'WhatsApp sent', 'Reminder 1', 'Reminder 2', 'No reply', 'Bounced') then null else replied_at end,
    valid_quote = case when st <> 'Quoted' then null when p ? 'valid_quote' then (p ->> 'valid_quote')::boolean else coalesce(valid_quote, true) end,
    note = case when p ? 'note' then nullif(btrim(p ->> 'note'), '') else note end, updated_at = now()
  where rfq_no = r.rfq_no and supplier_id = x.supplier_id returning * into x;
  msg := s.supplier_id || ' ' || s.name || ': ' || old || ' -> ' || st || case when st = 'Quoted' then case when x.valid_quote then ' (valid)' else ' (not valid)' end else '' end
    || coalesce(' - ' || nullif(btrim(p ->> 'note'), ''), '');
  if st in ('Replied', 'Quoted', 'Declined') and s.verification <> 'Verified' then
    update suppliers set verification = 'Verified', verification_note = 'replied to ' || r.rfq_no, verified_at = now(), updated_at = now(), updated_by = me.id where supplier_id = s.supplier_id;
    perform crm_log('supplier', s.supplier_id, s.name || ': verification ' || s.verification || ' -> Verified - replied to ' || r.rfq_no);
  elsif st = 'Bounced' and s.verification <> 'Failed' and not exists (select 1 from supplier_contacts c where c.supplier_id = s.supplier_id and (coalesce(c.whatsapp, '') <> '' or coalesce(c.phone, '') <> '')) then
    update suppliers set verification = 'Failed', verification_note = 'email bounced (' || r.rfq_no || '), no phone on file', updated_at = now(), updated_by = me.id where supplier_id = s.supplier_id;
    perform crm_log('supplier', s.supplier_id, s.name || ': verification ' || s.verification || ' -> Failed - email bounced, no phone on file');
  end if;
  if old is distinct from st or oldv is distinct from x.valid_quote or nullif(btrim(coalesce(p ->> 'note', '')), '') is not null then perform crm_log('rfq', r.rfq_no, msg); end if;
  perform crm_rfqauto(r.rfq_no);
  return crm_out(jsonb_build_object('recipient', crm_recj(x), 'rfq_status', (select status from rfqs where rfq_no = r.rfq_no)));
end $$;

/* RFQ status by hand: Short (goal guard), Approval sent, Awarded, Cancelled - or back to automatic (status 'auto') */
create or replace function public.crm_rfqstatus(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public as $$
declare me profiles := crm_need(true); r rfqs := crm_rfqget(p ->> 'rfq_no'); st text := coalesce(p ->> 'status', ''); note text := btrim(coalesce(p ->> 'note', ''));
begin
  if st not in ('auto', 'Short', 'Approval sent', 'Awarded', 'Cancelled') then raise exception 'Status must be Short, Approval sent, Awarded, Cancelled or auto'; end if;
  if st = 'Cancelled' and length(note) < 3 then raise exception 'Give the reason for cancelling'; end if;
  update rfqs set status = case when st = 'auto' then 'Draft' else st end, status_note = nullif(note, ''), updated_at = now(), updated_by = me.id where rfq_no = r.rfq_no;
  if st = 'auto' then perform crm_rfqauto(r.rfq_no); end if;
  perform crm_log('rfq', r.rfq_no, r.rfq_no || ': status ' || r.status || ' -> ' || (select status from rfqs where rfq_no = r.rfq_no) || coalesce(' - ' || nullif(note, ''), ''));
  return crm_out(jsonb_build_object('rfq', crm_rfqj(crm_rfqget(r.rfq_no))));
end $$;

