--
-- Security model
--   * Every person signs in with their own email + password (Supabase Auth). Public sign-up must be OFF.
--   * profiles.role: admin (users + everything) · qs (all data changes) · viewer (read only) · pm / site (v7, read only for now).
--   * The first account created becomes admin; later accounts start as viewer until the admin changes them.
--   * Tables are read-only through row-level security (signed-in, active users only).
--     All changes go through the crm_* functions below (SECURITY DEFINER) which check the role and the business rules
--     (lock, one draft revision, approved = locked …) and write the activity log.
--   * Files stay in Google Drive (Apps Script file service); only links are stored here.
-- =====================================================================================================

-- ---------- tables ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  full_name text default '',
  role text not null default 'viewer' check (role in ('admin', 'qs', 'pm', 'site', 'viewer')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.tenders (
  arza_no text primary key check (arza_no ~ '^T\d+$'),
  tender_ref text, project_no text, title text, title_en text, client text, client_group text, location text,
  tender_type text, id_scheme text,
  site_visit_date date, closing_date timestamp, status text, our_sum numeric(16, 2), completion_period text, submitted_date date,
  locked text not null default 'N' check (locked in ('Y', 'N')), locked_at timestamptz,
  result_date date, winner text, winning_sum numeric(16, 2), diff_pct numeric(9, 4), result_source text,
  workbook_file text, folder_link text, notes text,
  contract_sum numeric(16, 2), contract_rev text,
  created_at timestamptz default now(), updated_at timestamptz default now(),
  created_by uuid, updated_by uuid
);

create table if not exists public.bq_items (
  id bigint generated by default as identity primary key,
  arza_no text not null references public.tenders (arza_no) on update cascade on delete cascade,
  bq_set text not null,                      -- Tendered | R1 | R2 …
  item_id text not null,
  bill text, page text, item text, heading text, description text, unit text,
  qty numeric, rate numeric, amount numeric(16, 2),
  provisional text, remarks text, source text,
  imported_at timestamptz default now(),
  unique (arza_no, bq_set, item_id)
);
create index if not exists bq_items_set on public.bq_items (arza_no, bq_set);

create table if not exists public.asbuilt_items (
  id bigint generated by default as identity primary key,
  arza_no text not null references public.tenders (arza_no) on update cascade on delete cascade,
  measure_set text not null,
  item_ref_raw text, item_id text, match_status text, level text, location text, description text, unit text,
  nos numeric, l numeric, w numeric, h numeric, qty numeric,
  remark text, measured_by text, measured_date text, source_file text, source_row text,
  imported_at timestamptz default now()
);
create index if not exists asbuilt_set on public.asbuilt_items (arza_no, measure_set);

create table if not exists public.revisions (
  arza_no text not null references public.tenders (arza_no) on update cascade on delete cascade,
  rev text not null check (rev ~ '^R\d+$'),
  status text not null default 'Draft' check (status in ('Draft', 'Approved', 'Void')),
  based_on text, description text, lines int, rev_sum numeric(16, 2), base_sum numeric(16, 2), tender_sum numeric(16, 2),
  approved_date date, arza_rep text, client_rep text, client_org text, letter_ref text, document text, doc_link text,
  approved_at timestamptz, void_reason text, notes text,
  created_at timestamptz default now(), updated_at timestamptz default now(),
  created_by uuid, approved_by uuid,
  primary key (arza_no, rev)
);

create table if not exists public.activity_log (
