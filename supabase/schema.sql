/* create (no rev) or update a Draft revision: record + all its lines */
create or replace function public.crm_saverevision(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public as $$
declare me profiles := crm_need(true); t tenders := crm_tender(p ->> 'arza_no'); rec revisions; cur revisions; dr text; removed int; m jsonb := coalesce(p -> 'meta', '{}');
begin
  if t.locked <> 'Y' then raise exception 'Lock the tendered BQ of % first - revisions are made after submission', t.arza_no; end if;
  if coalesce(p ->> 'rev', '') = '' then
    select rev into dr from revisions where arza_no = t.arza_no and status = 'Draft' limit 1;
    if dr is not null then raise exception '% is still a draft - approve or delete it before starting another revision', dr; end if;
    cur := crm_current(t.arza_no);
    rec.arza_no := t.arza_no; rec.status := 'Draft'; rec.based_on := coalesce(cur.rev, 'Tendered'); rec.created_at := now(); rec.created_by := me.id;
    rec.rev := 'R' || (coalesce((select max(crm_revn(rev)) from revisions where arza_no = t.arza_no), 0) + 1);
  else
    select * into rec from revisions where arza_no = t.arza_no and rev = p ->> 'rev';
    if not found then raise exception 'Revision % not found', p ->> 'rev'; end if;
    if rec.status <> 'Draft' then raise exception '% is % and locked - start a new revision instead', rec.rev, rec.status; end if;
  end if;
  if jsonb_array_length(coalesce(p -> 'items', '[]')) = 0 then raise exception 'A revision needs at least one BQ line'; end if;
  if m ? 'description' then rec.description := btrim(m ->> 'description'); end if;
  if m ? 'notes' then rec.notes := btrim(m ->> 'notes'); end if;
  if coalesce(rec.description, '') = '' then raise exception 'Describe the revision (e.g. "Rationalization to budget, JKR letter …")'; end if;
  delete from bq_items where arza_no = t.arza_no and bq_set = rec.rev; get diagnostics removed = row_count;
  rec.lines := crm_write_bq(t.arza_no, rec.rev, p -> 'items', true);
  rec.rev_sum := crm_set_sum(t.arza_no, rec.rev); rec.base_sum := crm_set_sum(t.arza_no, rec.based_on); rec.tender_sum := t.our_sum;
  rec.updated_at := now();
  if coalesce(p #>> '{file,name}', '') <> '' then
    rec.notes := coalesce(nullif(rec.notes, '') || ' | ', '') || 'Workbook: ' || (p #>> '{file,name}');
    update tenders set folder_link = coalesce(nullif(p #>> '{file,folder_link}', ''), folder_link) where arza_no = t.arza_no;
  end if;
  insert into revisions select rec.*
  on conflict (arza_no, rev) do update set (status, based_on, description, lines, rev_sum, base_sum, tender_sum, notes, updated_at)
    = (excluded.status, excluded.based_on, excluded.description, excluded.lines, excluded.rev_sum, excluded.base_sum, excluded.tender_sum, excluded.notes, excluded.updated_at);
  perform crm_log('revision', t.arza_no, case when removed > 0 then 'Updated draft ' else 'New draft ' end || rec.rev || ' (from ' || rec.based_on || '): ' || rec.lines
    || ' lines, B$' || crm_m(rec.rev_sum) || ' (' || crm_diff_txt(rec.rev_sum, rec.base_sum) || ' vs ' || rec.based_on || ')' || coalesce('; ' || nullif(p #>> '{file,name}', ''), ''));
  select * into rec from revisions where arza_no = t.arza_no and rev = rec.rev;
  return crm_out(jsonb_build_object('revision', crm_rj(rec), 'tender', crm_tj(crm_tender(t.arza_no))));
end $$;

/* approval record (both parties): locks the revision and makes it the contract BQ */
create or replace function public.crm_approverevision(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public as $$
declare me profiles := crm_need(true); t tenders := crm_tender(p ->> 'arza_no'); a jsonb := coalesce(p -> 'approval', '{}'); rec revisions; k text;
begin
  select * into rec from revisions where arza_no = t.arza_no and rev = p ->> 'rev';
  if not found then raise exception 'Revision % not found', p ->> 'rev'; end if;
  if rec.status <> 'Draft' then raise exception '% is already %', rec.rev, rec.status; end if;
  foreach k in array array['approved_date', 'arza_rep', 'client_rep', 'letter_ref'] loop
    if btrim(coalesce(a ->> k, '')) = '' then
      raise exception 'Give the %', case k when 'approved_date' then 'approval date' when 'arza_rep' then 'ARZA representative' when 'client_rep' then 'client representative' else 'letter / document ref' end;
    end if;
  end loop;
  if coalesce(rec.lines, 0) <= 0 then raise exception '% has no BQ lines', rec.rev; end if;
  update revisions set status = 'Approved', approved_date = (a ->> 'approved_date')::date, arza_rep = btrim(a ->> 'arza_rep'), client_rep = btrim(a ->> 'client_rep'),
    client_org = nullif(btrim(coalesce(a ->> 'client_org', '')), ''), letter_ref = btrim(a ->> 'letter_ref'),
