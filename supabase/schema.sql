    approved_at = now(), approved_by = me.id, updated_at = now()
  where arza_no = t.arza_no and rev = rec.rev
  returning * into rec;
  update tenders set contract_sum = rec.rev_sum, contract_rev = rec.rev, updated_at = now(), updated_by = me.id,
    folder_link = coalesce(nullif(p #>> '{file,folder_link}', ''), folder_link) where arza_no = t.arza_no;
