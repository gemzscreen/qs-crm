);
create index if not exists asbuilt_set on public.asbuilt_items (arza_no, measure_set);

create table if not exists public.revisions (
  arza_no text not null references public.tenders (arza_no) on update cascade on delete cascade,
  rev text not null check (rev ~ '^R\d+$'),
  status text not null default 'Draft' check (status in ('Draft', 'Approved', 'Void')),
  based_on text, description text, lines int, rev_sum numeric(16, 2), base_sum numeric(16, 2), tender_sum numeric(16, 2),
