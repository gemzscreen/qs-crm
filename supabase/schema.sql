-- ---------- small helpers ----------
create or replace function public.crm_today() returns date language sql stable as
$$ select (now() at time zone 'Asia/Brunei')::date $$;

create or replace function public.crm_ft(x timestamp) returns text language sql immutable as
$$ select case when x is null then null when x::time = '00:00' then to_char(x, 'YYYY-MM-DD') else to_char(x, 'YYYY-MM-DD HH24:MI') end $$;
create or replace function public.crm_ftz(x timestamptz) returns text language sql stable as
$$ select public.crm_ft(x at time zone 'Asia/Brunei') $$;
create or replace function public.crm_fd(x date) returns text language sql immutable as
$$ select to_char(x, 'YYYY-MM-DD') $$;
create or replace function public.crm_m(x numeric) returns text language sql immutable as
$$ select to_char(coalesce(x, 0), 'FM999,999,999,990.00') $$;
create or replace function public.crm_short(x text) returns text language sql immutable as
$$ select case when coalesce(x, '') = '' then '(blank)' when length(x) > 40 then left(x, 37) || '...' else x end $$;
create or replace function public.crm_diff_txt(a numeric, b numeric) returns text language sql immutable as $$
  select case when round(coalesce(a,0) - coalesce(b,0), 2) >= 0 then '+' else '-' end || 'B$' || public.crm_m(abs(round(coalesce(a,0) - coalesce(b,0), 2)))
    || case when coalesce(b, 0) <> 0 then ', ' || case when a - b >= 0 then '+' else '' end || to_char((a - b) / b * 100, 'FM9999990.00') || '%' else '' end
$$;
create or replace function public.crm_revn(r text) returns int language sql immutable as
$$ select coalesce((substring(r from '^[Rr](\d+)$'))::int, 0) $$;

/* numbers from the app: JSON number, "1,250.50", "" or null */
create or replace function public.crm_isnum(x jsonb) returns boolean language plpgsql immutable as $$
begin
  if x is null or jsonb_typeof(x) = 'null' then return true; end if;
  if jsonb_typeof(x) = 'number' then return true; end if;
  if jsonb_typeof(x) = 'string' then
    if btrim(x #>> '{}') = '' then return true; end if;
    perform replace(x #>> '{}', ',', '')::numeric; return true;
  end if;
  return false;
exception when others then return false;
end $$;
create or replace function public.crm_n(x jsonb) returns numeric language plpgsql immutable as $$
begin
  if x is null or jsonb_typeof(x) not in ('number', 'string') then return null; end if;
  if jsonb_typeof(x) = 'string' and btrim(x #>> '{}') = '' then return null; end if;
  return replace(x #>> '{}', ',', '')::numeric;
exception when others then return null;
end $$;

create or replace function public.crm_editable() returns text[] language sql immutable as $$
  select array['tender_ref', 'project_no', 'title', 'title_en', 'client', 'client_group', 'location', 'tender_type', 'id_scheme',
    'site_visit_date', 'closing_date', 'status', 'our_sum', 'completion_period', 'submitted_date', 'workbook_file', 'folder_link', 'notes']
$$;

/* keep only editable fields; "" -> null; numbers checked */
create or replace function public.crm_clean(f jsonb) returns jsonb language plpgsql immutable as $$
declare out jsonb;
begin
  select coalesce(jsonb_object_agg(k, case when v = '""'::jsonb then 'null'::jsonb when jsonb_typeof(v) = 'string' then to_jsonb(btrim(v #>> '{}')) else v end), '{}')
    into out from jsonb_each(coalesce(f, '{}')) e(k, v) where k = any (public.crm_editable());
  if out ? 'our_sum' and jsonb_typeof(out -> 'our_sum') <> 'null' then
    if public.crm_n(out -> 'our_sum') is null then raise exception 'Our sum must be a number'; end if;
    out := out || jsonb_build_object('our_sum', public.crm_n(out -> 'our_sum'));
  end if;
  if out ? 'closing_date' and jsonb_typeof(out -> 'closing_date') = 'string' then
    out := out || jsonb_build_object('closing_date', replace(out ->> 'closing_date', 'T', ' '));
  end if;
  return out;
end $$;

-- ---------- JSON shapes (same as the Apps Script API: dates as text in Brunei time) ----------
create or replace function public.crm_tj(t public.tenders) returns jsonb language sql stable as $$
  select to_jsonb(t) - 'created_by' - 'updated_by' || jsonb_build_object(
    'site_visit_date', public.crm_fd(t.site_visit_date), 'closing_date', public.crm_ft(t.closing_date),
    'submitted_date', public.crm_fd(t.submitted_date), 'result_date', public.crm_fd(t.result_date),
    'locked_at', public.crm_ftz(t.locked_at), 'created_at', public.crm_ftz(t.created_at), 'updated_at', public.crm_ftz(t.updated_at))
$$;
create or replace function public.crm_bj(b public.bq_items) returns jsonb language sql stable as
$$ select to_jsonb(b) - 'id' || jsonb_build_object('imported_at', public.crm_ftz(b.imported_at)) $$;
create or replace function public.crm_aj(a public.asbuilt_items) returns jsonb language sql stable as
$$ select to_jsonb(a) - 'id' || jsonb_build_object('imported_at', public.crm_ftz(a.imported_at)) $$;
create or replace function public.crm_rj(r public.revisions) returns jsonb language sql stable as $$
  select to_jsonb(r) - 'created_by' - 'approved_by' || jsonb_build_object('approved_date', public.crm_fd(r.approved_date), 'approved_at', public.crm_ftz(r.approved_at),
    'created_at', public.crm_ftz(r.created_at), 'updated_at', public.crm_ftz(r.updated_at))
$$;
create or replace function public.crm_lj(l public.activity_log) returns jsonb language sql stable as
$$ select jsonb_build_object('timestamp', public.crm_ftz(l.ts), 'action', l.action, 'arza_no', l.arza_no, 'detail', l.detail, 'user', l.user_name) $$;
create or replace function public.crm_pj(p public.profiles) returns jsonb language sql stable as
$$ select jsonb_build_object('id', p.id, 'email', p.email, 'full_name', p.full_name, 'role', p.role, 'active', p.active, 'created_at', public.crm_ftz(p.created_at)) $$;

-- ---------- access, log ----------
create or replace function public.crm_can_read() returns boolean language sql stable security definer set search_path = public as
$$ select exists (select 1 from profiles where id = auth.uid() and active) $$;

create or replace function public.crm_need(p_write boolean default false, p_admin boolean default false) returns public.profiles
language plpgsql stable security definer set search_path = public as $$
declare me profiles;
begin
  if auth.uid() is null then raise exception 'AUTH: Not signed in'; end if;
  select * into me from profiles where id = auth.uid();
  if not found or not me.active then raise exception 'AUTH: This account has no access to QS CRM - ask the admin'; end if;
  if p_admin and me.role <> 'admin' then raise exception 'Only the admin can do this'; end if;
  if p_write and me.role not in ('admin', 'qs') then raise exception 'Read-only account (%) - only QS and admin users can make changes', me.role; end if;
  return me;
end $$;

create or replace function public.crm_log(p_action text, p_no text, p_detail text) returns void
language sql security definer set search_path = public as $$
  insert into activity_log (action, arza_no, detail, user_id, user_name)
  values (p_action, p_no, p_detail, auth.uid(),
    coalesce((select coalesce(nullif(full_name, ''), email) from profiles where id = auth.uid()), 'system'))
$$;
/* result + the log lines written in this call (the app shows them without a second request) */
create or replace function public.crm_out(j jsonb) returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(j, '{}'::jsonb) || jsonb_build_object('_log',
    coalesce((select jsonb_agg(crm_lj(l) order by l.id) from activity_log l where l.tx = txid_current()), '[]'::jsonb))
$$;

create or replace function public.crm_tender(p_no text) returns public.tenders language plpgsql stable security definer set search_path = public as $$
declare t tenders;
begin
  select * into t from tenders where arza_no = p_no;
  if not found then raise exception 'Tender % not found', coalesce(p_no, '(blank)'); end if;
  return t;
end $$;
create or replace function public.crm_next_no() returns text language sql stable security definer set search_path = public as $$
  select 'T' || case when n < 10 then '0' || n::text else n::text end
  from (select coalesce(max((substring(arza_no from '^T(\d+)$'))::int), 0) + 1 as n from tenders) x
$$;
create or replace function public.crm_check_row(t public.tenders) returns void language plpgsql stable security definer set search_path = public as $$
begin
  if t.status is not null and not exists (select 1 from lists where list = 'status' and value = t.status) then raise exception 'Unknown status %', t.status; end if;
  if coalesce(t.title, '') = '' and coalesce(t.tender_ref, '') = '' then raise exception 'Give at least a title or the client tender ref'; end if;
end $$;
create or replace function public.crm_lists() returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_object_agg(list, vals), '{}') from (select list, jsonb_agg(value order by sort, value) vals from lists group by list) x
$$;

/* BQ lines -> bq_items (Tendered or a revision set). p_calc: amount = qty x rate (revisions) */
create or replace function public.crm_write_bq(p_no text, p_set text, p_items jsonb, p_calc boolean default false) returns int
language plpgsql security definer set search_path = public as $$
declare n int; bad text;
begin
  select coalesce(x ->> 'item_id', '') into bad from jsonb_array_elements(coalesce(p_items, '[]')) x
    where btrim(coalesce(x ->> 'item_id', '')) = '' limit 1;
  if found then raise exception 'A BQ line has no item ID'; end if;
  select btrim(x ->> 'item_id') into bad from jsonb_array_elements(p_items) x group by btrim(x ->> 'item_id') having count(*) > 1 limit 1;
  if found then raise exception 'Item ID % is used twice', bad; end if;
  select btrim(x ->> 'item_id') || ': ' || k || ' "' || (x ->> k) || '" is not a number' into bad
    from jsonb_array_elements(p_items) x, unnest(array['qty', 'rate', 'amount']) k where not crm_isnum(x -> k) limit 1;
  if found then raise exception '%', bad; end if;
  insert into bq_items (arza_no, bq_set, item_id, bill, page, item, heading, description, unit, qty, rate, amount, provisional, remarks, source, imported_at)
  select p_no, p_set, btrim(x ->> 'item_id'), x ->> 'bill', x ->> 'page', x ->> 'item', x ->> 'heading', x ->> 'description', x ->> 'unit',
    crm_n(x -> 'qty'), crm_n(x -> 'rate'),
    case when p_calc and crm_n(x -> 'qty') is not null and crm_n(x -> 'rate') is not null then round(crm_n(x -> 'qty') * crm_n(x -> 'rate'), 2)
         when p_calc then coalesce(crm_n(x -> 'amount'), 0) else crm_n(x -> 'amount') end,
    case when (coalesce(x ->> 'heading', '') || ' ' || coalesce(x ->> 'description', '') || ' ' || coalesce(x ->> 'remarks', '')) ~* 'provisional|prov\.? sum' then 'Y' else 'N' end,
    x ->> 'remarks', x ->> 'source', now()
  from jsonb_array_elements(coalesce(p_items, '[]')) x;
  get diagnostics n = row_count;
  return n;
end $$;

create or replace function public.crm_revs(p_no text) returns jsonb language sql stable security definer set search_path = public as
$$ select coalesce(jsonb_agg(crm_rj(r) order by crm_revn(r.rev)), '[]') from revisions r where r.arza_no = p_no $$;
create or replace function public.crm_current(p_no text) returns public.revisions language sql stable security definer set search_path = public as
$$ select * from revisions where arza_no = p_no and status = 'Approved' order by crm_revn(rev) desc limit 1 $$;
create or replace function public.crm_set_sum(p_no text, p_set text) returns numeric language sql stable security definer set search_path = public as
$$ select round(coalesce(sum(amount), 0), 2) from bq_items where arza_no = p_no and bq_set = p_set $$;
create or replace function public.crm_bqj(p_no text, p_set text) returns jsonb language sql stable security definer set search_path = public as
$$ select coalesce(jsonb_agg(crm_bj(b) order by b.id), '[]') from bq_items b where b.arza_no = p_no and b.bq_set = p_set $$;

create or replace function public.crm_do_lock(p_no text, p_reason text) returns void language plpgsql security definer set search_path = public as $$
declare t tenders := crm_tender(p_no);
begin
  if t.locked = 'Y' then return; end if;
  update tenders set locked = 'Y', locked_at = now(), updated_at = now(), updated_by = auth.uid(),
    status = case when status is null or status in ('Prospect', 'Pricing') then 'Submitted' else status end,
    submitted_date = coalesce(submitted_date, crm_today())
  where arza_no = p_no;
  perform crm_log('lock', p_no, 'Tendered BQ locked, sum B$' || crm_m(t.our_sum) || coalesce(' - ' || nullif(p_reason, ''), ''));
end $$;

