    document = coalesce(nullif(p #>> '{file,name}', ''), document), doc_link = coalesce(nullif(p #>> '{file,url}', ''), doc_link),
    approved_at = now(), approved_by = me.id, updated_at = now()
  where arza_no = t.arza_no and rev = rec.rev
  returning * into rec;
  update tenders set contract_sum = rec.rev_sum, contract_rev = rec.rev, updated_at = now(), updated_by = me.id,
    folder_link = coalesce(nullif(p #>> '{file,folder_link}', ''), folder_link) where arza_no = t.arza_no;
  perform crm_log('approve', t.arza_no, rec.rev || ' approved ' || crm_fd(rec.approved_date) || ', ref ' || rec.letter_ref || ' (ARZA: ' || rec.arza_rep || '; client: ' || rec.client_rep
    || coalesce(', ' || rec.client_org, '') || '). Contract sum B$' || crm_m(rec.rev_sum) || ' (' || crm_diff_txt(rec.rev_sum, rec.tender_sum) || ' vs tendered)'
    || coalesce('; document ' || rec.document, '; no document attached'));
  return crm_out(jsonb_build_object('revision', crm_rj(rec), 'tender', crm_tj(crm_tender(t.arza_no))));
end $$;

