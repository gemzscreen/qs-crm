/* RFQ status from its recipients: Draft until the first contact; Sent; Chasing after a reminder; Comparison at >= 3 valid quotes.
   Short / Approval sent / Awarded / Cancelled are set by hand and kept. */
create or replace function public.crm_rfqauto(p_no text) returns void language plpgsql security definer set search_path = public as $$
declare r rfqs := crm_rfqget(p_no); st text;
begin
  if r.status in ('Short', 'Approval sent', 'Awarded', 'Cancelled') then return; end if;
  select case when count(*) filter (where status = 'Quoted' and valid_quote) >= 3 then 'Comparison'
              when count(*) filter (where reminder1_at is not null or reminder2_at is not null) > 0 then 'Chasing'
              when count(*) filter (where status <> 'Not contacted') > 0 then 'Sent' else 'Draft' end into st
  from rfq_recipients where rfq_no = r.rfq_no;
  update rfqs set status = st, sent_at = case when st <> 'Draft' then coalesce(sent_at, (select min(least(coalesce(emailed_at, whatsapp_at), coalesce(whatsapp_at, emailed_at))) from rfq_recipients where rfq_no = r.rfq_no), now()) else sent_at end
  where rfq_no = r.rfq_no and (status is distinct from st or (st <> 'Draft' and sent_at is null));
end $$;

