/* void the latest approved revision (needs a reason, lines are kept) */
create or replace function public.crm_voidrevision(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public as $$
declare me profiles := crm_need(true); t tenders := crm_tender(p ->> 'arza_no'); cur revisions; prev revisions; dr revisions;
begin
  if length(btrim(coalesce(p ->> 'reason', ''))) < 5 then raise exception 'Give a reason to void the revision'; end if;
  cur := crm_current(t.arza_no);
  if cur.rev is null or cur.rev <> coalesce(p ->> 'rev', '') then
    raise exception 'Only the latest approved revision%can be voided', coalesce(' (' || cur.rev || ') ', ' '); end if;
  select * into dr from revisions where arza_no = t.arza_no and status = 'Draft' limit 1;
  if dr.rev is not null then raise exception 'Delete draft % first (it is based on %)', dr.rev, dr.based_on; end if;
  update revisions set status = 'Void', void_reason = btrim(p ->> 'reason'), updated_at = now() where arza_no = t.arza_no and rev = cur.rev returning * into cur;
  prev := crm_current(t.arza_no);
