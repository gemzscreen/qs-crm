      'currency', q.currency, 'lines', (select jsonb_agg(jsonb_build_object('line', l.line, 'unit_price', l.unit_price, 'moq', l.moq, 'brand', coalesce(l.brand, '')) order by l.line) from quote_lines l where l.quote_id = q.id))
      else null end);
