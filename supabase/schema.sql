create or replace function public.crm_setuser(p jsonb default '{}') returns jsonb language plpgsql security definer set search_path = public as $$
declare me profiles := crm_need(false, true); u profiles; ch text[] := '{}';
begin
  select * into u from profiles where id = (p ->> 'id')::uuid;
  if not found then raise exception 'User not found'; end if;
  if p ? 'role' and (p ->> 'role') not in ('admin', 'qs', 'pm', 'site', 'viewer') then raise exception 'Unknown role %', p ->> 'role'; end if;
  if u.role = 'admin' and u.active and ((p ? 'role' and p ->> 'role' <> 'admin') or (p ? 'active' and not (p ->> 'active')::boolean))
     and not exists (select 1 from profiles where role = 'admin' and active and id <> u.id) then
    raise exception 'There must be at least one active admin';
  end if;
  if p ? 'role' and p ->> 'role' <> u.role then ch := ch || ('role ' || u.role || ' -> ' || (p ->> 'role')); end if;
  if p ? 'active' and (p ->> 'active')::boolean <> u.active then ch := ch || case when (p ->> 'active')::boolean then 'activated' else 'deactivated' end; end if;
  if p ? 'full_name' and btrim(p ->> 'full_name') <> coalesce(u.full_name, '') then ch := ch || ('name: ' || btrim(p ->> 'full_name')); end if;
  update profiles set role = coalesce(p ->> 'role', role), active = coalesce((p ->> 'active')::boolean, active),
    full_name = coalesce(btrim(p ->> 'full_name'), full_name) where id = u.id returning * into u;
  if cardinality(ch) > 0 then perform crm_log('user', null, u.email || ': ' || array_to_string(ch, ', ')); end if;
  return crm_out(crm_pj(u));
end $$;

-- ---------- one-time data import from the Google Sheet (downloaded as QS CRM DB.xlsx) ----------
