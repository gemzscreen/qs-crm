  from jsonb_populate_recordset(null::asbuilt_items, coalesce(p -> 'asbuilt', '[]'));
  get diagnostics n_a = row_count;
  insert into revisions select * from jsonb_populate_recordset(null::revisions, coalesce(p -> 'revisions', '[]'));
  get diagnostics n_r = row_count;
  insert into activity_log (ts, action, arza_no, detail, user_name, tx)
