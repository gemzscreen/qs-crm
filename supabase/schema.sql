  get diagnostics n_l = row_count;
  if jsonb_typeof(p -> 'lists') = 'object' then
    insert into lists (list, value, sort)
    select k, v, o::int from jsonb_each(p -> 'lists') e(k, arr), jsonb_array_elements_text(arr) with ordinality x(v, o)
    on conflict (list, value) do update set sort = excluded.sort;
  end if;
  perform crm_log('migrate', null, 'Imported from ' || coalesce(nullif(p ->> 'file_name', ''), 'QS CRM DB.xlsx') || ': ' || n_t || ' tenders, ' || n_b || ' BQ lines, '
    || n_a || ' as-built lines, ' || n_r || ' revisions, ' || n_l || ' log lines' || case when existing > 0 then ' (replaced ' || existing || ' tenders)' else '' end);
  return crm_out(jsonb_build_object('tenders', n_t, 'bq', n_b, 'asbuilt', n_a, 'revisions', n_r, 'log', n_l));
end $$;

